def run(*args):
    result = subprocess.run(args, capture_output=True)
    return result.returncode, (result.stdout + result.stderr).decode(errors="replace")


def main():
    for needed in ("tillpoint", "tests", "NOTES.md", ".git"):
        if not os.path.exists(needed):
            sys.exit(f"Run this from the project folder (I cannot see '{needed}'). Run make_commits.py first.")
    code, log = run("git", "log", "--format=%s")
    if "Add regression tests for reports 1-5" not in log:
        sys.exit("Run make_commits.py first, then this script.")
    if MESSAGE in log:
        print("Report 6 is already committed:\n" + run("git", "log", "--oneline", "-3")[1])
        return

    for path, data in FILES:
        with open(path, "wb") as f:
            f.write(base64.b64decode("".join(data.split())))

    code, out = run(sys.executable, "-m", "unittest", "discover", "-s", "tests")
    print(out.strip().splitlines()[-1] if out.strip() else "")
    if code != 0:
        print(out)
        sys.exit("Tests failed, so I did not commit. Send me a screenshot of this.")

    run("git", "add", "-A")
    code, out = run("git", "commit", "-m", MESSAGE)
    if code != 0:
        sys.exit("Commit failed:\n" + out)
    print(run("git", "log", "--oneline", "-3")[1])
    print("Done. The Report 6 commit is the first line above.")


main()
